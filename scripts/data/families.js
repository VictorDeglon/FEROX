/**
 * Exercise families, and the axes each one genuinely varies along.
 *
 * The catalogue is generated from this rather than typed out one entry at a
 * time, because a thousand hand-written rows drift: the same movement ends up
 * with two different muscle lists depending on which afternoon it was added.
 *
 * The rule for an axis is that **every combination it produces must be a real
 * exercise**. `implements × angles` is only allowed where every cell of that
 * grid is something people actually do — a decline cable press is real, a
 * decline lateral raise is not, so lateral raises do not have an angle axis.
 * Anything that does not fit a grid goes in `extras` and is written out in full.
 *
 *   gear   the implement, for filtering: barbell, dumbbell, machine, cable,
 *          smith, kettlebell, band, bodyweight, plyo, cardio, other
 *   equip  the LEAST kit it needs — matches EQUIP_RANK in seed.js, so a
 *          bodyweight movement is available to everyone
 */

